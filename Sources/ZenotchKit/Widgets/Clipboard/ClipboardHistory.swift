import Foundation

struct ClipboardEntry: Identifiable, Equatable {
    let id: UUID
    let text: String
    let copiedAt: Date

    init(text: String, copiedAt: Date, id: UUID = UUID()) {
        self.id = id
        self.text = text
        self.copiedAt = copiedAt
    }

    var preview: String {
        text.split(whereSeparator: \.isNewline).first.map(String.init)?
            .trimmingCharacters(in: .whitespaces) ?? ""
    }
}

struct ClipboardHistory: Equatable {
    /// Password managers mark secrets with these pasteboard types (nspasteboard.org convention).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    let limit: Int
    private(set) var entries: [ClipboardEntry] = []

    init(limit: Int = 30) {
        self.limit = limit
    }

    static func shouldRecord(types: [String]) -> Bool {
        ignoredTypes.isDisjoint(with: types)
    }

    /// Re-copying an existing entry moves it to the top instead of duplicating it.
    mutating func record(_ text: String, at date: Date) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        entries.removeAll { $0.text == text }
        entries.insert(ClipboardEntry(text: text, copiedAt: date), at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
    }

    mutating func remove(id: UUID) {
        entries.removeAll { $0.id == id }
    }

    mutating func clear() {
        entries.removeAll()
    }
}
